package ch_02_operators.t02_relational_operators;

public class Relational_Operators {
    public static void main(String[] args) {
        int a = 10;
        int b = 5;
        System.out.println((a == b)); // false
        System.out.println((a != b)); // true
        System.out.println((a > b)); // true
        System.out.println((a < b)); // false
        System.out.println((a >= b)); // true
        System.out.println((a <= b)); // false
    }
}
