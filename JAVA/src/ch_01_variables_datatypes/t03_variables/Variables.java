package ch_01_variables_datatypes.t03_variables;

public class Variables {
    public static void main(String[] args) {
        int a = 10;
        int b = 5;
        System.out.println(a);
        System.out.println(b);

        String name = "surya";
        System.out.println(name);
    }
}

// Variables are containers used to store the data or values
// 1,2,3,4,5...     --> Literals
// a,b,name,age,... --> Variables
